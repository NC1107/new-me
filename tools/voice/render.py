#!/usr/bin/env python3
"""Renders the guided-session voice clips from manifest.json with Kokoro (Apache-2.0).

Setup, once:
    python3 -m venv .venv && .venv/bin/pip install kokoro-onnx soundfile
    Download kokoro-v1.0.onnx and voices-v1.0.bin from the kokoro-onnx release "model-files-v1.0"
    into one folder and pass it as --models.
    Needs ffmpeg and, on Linux, the system espeak-ng library: the copy bundled in the Python wheel
    looks for its data in the build machine's path, so point PHONEMIZER_ESPEAK_LIBRARY at the system
    one (for example /usr/lib64/libespeak-ng.so.1).

Run from the repo root:
    .venv/bin/python tools/voice/render.py --models /path/to/models [--only yoga_tree] [--missing]

Writes app/assets/audio/voice/<id>.m4a (AAC, mono) and app/lib/audio/voice_clips.dart, which gives
the app each clip's text (for the text-to-speech fallback) and length (for scheduling).
durations.json beside the manifest remembers each clip's length between runs.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "tools/voice/manifest.json"
OUT_DIR = ROOT / "app/assets/audio/voice"
DART = ROOT / "app/lib/audio/voice_clips.dart"
BITRATE = "28k"
TAIL_SECONDS = 0.25


def encode(wav: Path, out: Path) -> None:
    # Single-pass loudness normalization keeps every clip at one level, and the 28k mono AAC
    # keeps the whole set small enough to bundle.
    subprocess.run(
        [
            "ffmpeg", "-y", "-loglevel", "error", "-i", str(wav),
            "-af", "loudnorm=I=-18:TP=-2:LRA=7",
            "-ac", "1", "-ar", "24000", "-c:a", "aac", "-b:a", BITRATE, str(out),
        ],
        check=True,
    )


def dart_string(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def write_dart(clips: dict, seconds: dict) -> None:
    lines = [
        "// Generated by tools/voice/render.py from tools/voice/manifest.json. Do not edit by hand.",
        "",
        "import 'voice_clip.dart';",
        "",
        "const kVoiceClips = <String, VoiceClip>{",
    ]
    for clip_id, text in clips.items():
        lines.append(
            f"  {dart_string(clip_id)}: VoiceClip({dart_string(text)}, {seconds[clip_id]:.1f}),"
        )
    lines += ["};", ""]
    DART.write_text("\n".join(lines))
    subprocess.run(["dart", "format", str(DART)], check=False)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", required=True, type=Path)
    ap.add_argument("--only", help="render only ids starting with this prefix")
    ap.add_argument("--missing", action="store_true", help="skip clips that already have a file")
    args = ap.parse_args()

    manifest = json.loads(MANIFEST.read_text())
    clips = manifest["clips"]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    kokoro = Kokoro(str(args.models / "kokoro-v1.0.onnx"), str(args.models / "voices-v1.0.bin"))

    seconds_path = ROOT / "tools/voice/durations.json"
    seconds = json.loads(seconds_path.read_text()) if seconds_path.exists() else {}
    for clip_id, text in clips.items():
        out = OUT_DIR / f"{clip_id}.m4a"
        wanted = (not args.only or clip_id.startswith(args.only)) and not (
            args.missing and out.exists() and clip_id in seconds
        )
        if not wanted:
            continue
        samples, rate = kokoro.create(
            text, voice=manifest["voice"], speed=manifest["speed"], lang=manifest["lang"]
        )
        with tempfile.TemporaryDirectory() as tmp:
            wav = Path(tmp) / "clip.wav"
            sf.write(wav, samples, rate)
            encode(wav, out)
        seconds[clip_id] = len(samples) / rate + TAIL_SECONDS
        print(f"{clip_id}: {seconds[clip_id]:.1f}s", flush=True)

    stale = {p for p in OUT_DIR.glob("*.m4a") if p.stem not in clips}
    for p in stale:
        p.unlink()
    seconds = {k: v for k, v in seconds.items() if k in clips}
    seconds_path.write_text(json.dumps(seconds, indent=1, sort_keys=True) + "\n")
    missing = [c for c in clips if c not in seconds]
    if missing:
        print(f"not rendered: {missing}", file=sys.stderr)
        return 1
    write_dart(clips, seconds)
    total = sum(p.stat().st_size for p in OUT_DIR.glob("*.m4a"))
    print(f"{len(clips)} clips, {total / 1e6:.2f} MB, {sum(seconds.values()) / 60:.1f} min")
    return 0


if __name__ == "__main__":
    sys.exit(main())
